async function setup(client) {
  await client.query(`
    CREATE SCHEMA IF NOT EXISTS bookclub_l2;
    CREATE TABLE IF NOT EXISTS bookclub_l2.books (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title varchar(120) NOT NULL,
      author varchar(120) NOT NULL,
      seed_key varchar(60) UNIQUE
    );
    CREATE TABLE IF NOT EXISTS bookclub_l2.members (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      display_name varchar(60) NOT NULL,
      seed_key varchar(60) UNIQUE
    );
    CREATE TABLE IF NOT EXISTS bookclub_l2.meetings (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      book_id integer NOT NULL REFERENCES bookclub_l2.books(id),
      title varchar(120) NOT NULL CHECK (length(trim(title)) > 0),
      starts_at timestamptz NOT NULL,
      location varchar(200) NOT NULL CHECK (length(trim(location)) > 0),
      capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 50),
      description varchar(2000) NOT NULL DEFAULT '',
      seed_key varchar(60) UNIQUE,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS bookclub_l2.registrations (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      meeting_id integer NOT NULL REFERENCES bookclub_l2.meetings(id),
      member_id integer NOT NULL REFERENCES bookclub_l2.members(id),
      status varchar(12) NOT NULL CHECK (status IN ('active', 'cancelled')),
      created_at timestamptz NOT NULL DEFAULT now(),
      canceled_at timestamptz,
      UNIQUE (meeting_id, member_id),
      CHECK ((status = 'active' AND canceled_at IS NULL) OR (status = 'cancelled' AND canceled_at IS NOT NULL))
    );
    CREATE INDEX IF NOT EXISTS meetings_book_id_idx ON bookclub_l2.meetings(book_id);
    CREATE INDEX IF NOT EXISTS meetings_starts_at_idx ON bookclub_l2.meetings(starts_at);
    CREATE INDEX IF NOT EXISTS registrations_meeting_status_idx ON bookclub_l2.registrations(meeting_id, status);
  `);
}
module.exports = { setup };
